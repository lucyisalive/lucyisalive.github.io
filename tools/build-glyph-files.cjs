'use strict';

// Split the already-frozen local objects without downloading, normalizing,
// simplifying, or regenerating any stroke outline or median coordinate.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const zlib = require('node:zlib');
const ROOT = path.resolve(__dirname, '..');
const SOURCES = ['hanzi-data.js', 'curriculum-hanzi-data.js'];
const EXPECTED_COUNT = 167;
const sha256 = text => crypto.createHash('sha256').update(text).digest('hex');
const gzipBytes = text => zlib.gzipSync(Buffer.from(text), { level: 9 }).length;
const canonical = glyphs => JSON.stringify(Object.keys(glyphs).sort().map(char => [char, glyphs[char]]));

function readFrozenGlyphs(projectRoot = ROOT) {
  const context = vm.createContext({ window: {} });
  const sources = SOURCES.map(file => {
    const code = fs.readFileSync(path.join(projectRoot, file), 'utf8');
    vm.runInContext(code, context, { filename: file, timeout: 5000 });
    return { file, sha256: sha256(code) };
  });
  const glyphs = JSON.parse(JSON.stringify(context.window.HANZI_LOCAL_DATA));
  if (Object.keys(glyphs).length !== EXPECTED_COUNT) throw new Error('Expected exactly 167 frozen glyphs');
  for (const [char, data] of Object.entries(glyphs)) {
    if ([...char].length !== 1 || !Array.isArray(data.strokes) || !Array.isArray(data.medians) ||
      !data.strokes.length || data.strokes.length !== data.medians.length ||
      !data.strokes.every(stroke => typeof stroke === 'string' && stroke.length > 0) ||
      !data.medians.every(stroke => Array.isArray(stroke) && stroke.length > 0 && stroke.every(point =>
        Array.isArray(point) && point.length === 2 && point.every(Number.isFinite)))) {
      throw new Error('Invalid frozen glyph: ' + char);
    }
  }
  return { glyphs, sources };
}

function componentDependencies(projectRoot, glyphs) {
  const source = fs.readFileSync(path.join(projectRoot, 'game-source.html'), 'utf8');
  const match = source.match(/const COMPONENT_DECOMP\s*=\s*(\{[\s\S]*?\n\});/);
  if (!match) throw new Error('Cannot locate the original COMPONENT_DECOMP; review the source before building');
  const original = JSON.parse(JSON.stringify(vm.runInNewContext('(' + match[1] + ')', {}, { timeout: 1000 })));
  const dependencies = {}, excluded = {};
  for (const [char, parts] of Object.entries(original)) {
    if (!Object.hasOwn(glyphs, char)) continue;
    if (!Array.isArray(parts) || !parts.every(part => typeof part === 'string' && [...part].length === 1)) {
      throw new Error('Invalid original component list: ' + char);
    }
    const missing = parts.filter(part => !Object.hasOwn(glyphs, part));
    // Missing parts used to make the grader keep its whole-character path.
    // Never fill those gaps from an upstream service or invent new components.
    if (missing.length) excluded[char] = { parts: Array.from(parts), missing };
    else dependencies[char] = Array.from(parts);
  }
  return { dependencies, excluded };
}

function createGlyphFiles(projectRoot = ROOT) {
  const { glyphs, sources } = readFrozenGlyphs(projectRoot);
  const { dependencies, excluded } = componentDependencies(projectRoot, glyphs);
  const pinyinCode = fs.readFileSync(path.join(projectRoot, 'pinyin-data.js'), 'utf8');
  const pinyinContext = vm.createContext({ window: {} });
  vm.runInContext(pinyinCode, pinyinContext, { filename: 'pinyin-data.js', timeout: 5000 });
  const pinyinMap = pinyinContext.window.PINYIN_MAP || {};
  const version = sha256(canonical(glyphs));
  const catalog = { version, glyphCount: EXPECTED_COUNT, glyphs: {} };
  const manifest = {
    schemaVersion: 1, description: 'Exact JSON split of the existing frozen local glyph objects; no geometry changes',
    version, glyphCount: EXPECTED_COUNT,
    sources: sources.concat({ file: 'pinyin-data.js', sha256: sha256(pinyinCode) }),
    componentSource: 'game-source.html:COMPONENT_DECOMP', excludedComponents: excluded, glyphs: {},
  };
  const files = new Map(), gzipSizes = [];
  for (const char of Object.keys(glyphs).sort()) {
    const file = 'glyphs/' + char + '.json';
    const content = JSON.stringify(glyphs[char]) + '\n';
    const hash = sha256(content), compressed = gzipBytes(content);
    files.set(file, content);
    catalog.glyphs[char] = {
      url: 'glyphs/' + encodeURIComponent(char) + '.json?v=' + version,
      deps: dependencies[char] || [],
      pinyin: typeof pinyinMap[char] === 'string' ? pinyinMap[char] : '',
    };
    manifest.glyphs[char] = { file, sha256: hash, bytes: Buffer.byteLength(content),
      gzipBytes: compressed, strokeCount: glyphs[char].strokes.length, deps: dependencies[char] || [] };
    gzipSizes.push({ char, bytes: compressed });
  }
  const catalogCode = '/* Generated by node tools/build-glyph-files.cjs from the original 167 glyphs.\n' +
    '   Edit the frozen source files deliberately, then rebuild; do not edit this catalog by hand. */\n' +
    'window.HANZI_GLYPH_CATALOG=' + JSON.stringify(catalog) + ';\n';
  files.set('glyph-catalog.js', catalogCode);
  files.set('data/glyph-manifest.json', JSON.stringify(manifest, null, 2) + '\n');

  // Reparse the exact bytes that will be served, not an alternate representation.
  const reconstructed = Object.fromEntries(Object.keys(glyphs).map(char =>
    [char, JSON.parse(files.get(manifest.glyphs[char].file))]));
  if (canonical(reconstructed) !== canonical(glyphs)) throw new Error('The split changed glyph geometry');
  gzipSizes.sort((a, b) => a.bytes - b.bytes);
  const summary = { glyphCount: EXPECTED_COUNT, geometrySha256: version,
    catalogBytes: Buffer.byteLength(catalogCode), catalogGzipBytes: gzipBytes(catalogCode),
    glyphJsonBytes: Object.values(manifest.glyphs).reduce((sum, entry) => sum + entry.bytes, 0),
    glyphGzipBytes: { min: gzipSizes[0], median: gzipSizes[Math.floor(gzipSizes.length / 2)], max: gzipSizes[gzipSizes.length - 1] },
    dependencies, excludedComponents: excluded };
  return { files, catalog, manifest, glyphs, summary };
}

function writeGlyphFiles(result, outputRoot, check = false) {
  for (const [file, content] of result.files) {
    const target = path.join(outputRoot, file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
        throw new Error('Generated glyph asset differs: ' + file);
      }
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content);
    }
  }
}

function main(args = process.argv.slice(2)) {
  let outputRoot = ROOT, check = false;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') check = true;
    else if (args[i] === '--out' && args[i + 1]) outputRoot = path.resolve(ROOT, args[++i]);
    else throw new Error('Usage: node tools/build-glyph-files.cjs [--out directory] [--check]');
  }
  if (outputRoot !== ROOT && !outputRoot.startsWith(ROOT + path.sep)) {
    throw new Error('Output must stay inside this project');
  }
  const result = createGlyphFiles();
  writeGlyphFiles(result, outputRoot, check);
  console.log(JSON.stringify({ mode: check ? 'check' : 'build', outputRoot, ...result.summary }, null, 2));
}

module.exports = { readFrozenGlyphs, componentDependencies, createGlyphFiles, writeGlyphFiles, canonical };
if (require.main === module) {
  try { main(); }
  catch (error) { console.error('Glyph build failed: ' + error.message); process.exitCode = 1; }
}
